# 1. Printing to the console
print("Hello, World!")
print("Welcome to the AI Learning Journey.")

# 2. Variables
# Variables are used to store data. You don't need to declare a type.
name = "Alice"
age = 25

# 3. Printing variables (using f-strings for easy formatting)
print(f"My name is {name} and I am {age} years old.")

# 4. Basic Input
# We can ask the user for input
user_name = input("What is your name? ")
print(f"Nice to meet you, {user_name}!")
